# i take master.csv, forecasts.csv, and re-run the coefficient regression
# then dump everything as javascript variables in dashboard/data.js
# the html file loads that and renders three plotly charts
import pandas as pd
import numpy as np
import statsmodels.formula.api as smf
import json
from pathlib import Path
base = Path(__file__).parent.parent
master_path = base / "data/clean/master.csv"
fc_path = base / "data/clean/forecasts.csv"
out_path = base / "dashboard/data.js"

# affordability chart data
df = pd.read_csv(master_path)
df["date_iso"] = pd.to_datetime(df["date"], format="%Y-%m").dt.strftime("%Y-%m-%d")
affordability = {}
for city in df["city"].unique():
    s = df[df["city"] == city].sort_values("date_iso")
    affordability[city] = {
        "dates": s["date_iso"].tolist(),
        "mm":    s["median_multiple"].round(3).tolist(),
        "mdsr":  (s["mdsr"] * 100).round(2).tolist(),
    }
# coefficient regression
df["mdsr_pct"] = df["mdsr"] * 100
df["log_price"] = np.log(df["price_local"])
df["log_income"] = np.log(df["income"])
coefficients = {}
for city in df["city"].unique():
    sub = df[df["city"] == city]
    m = smf.ols(
        "mdsr_pct ~ rate + unemployment + log_price + log_income",
        data=sub
    ).fit(cov_type="HAC", cov_kwds={"maxlags": 6})
    ci = m.conf_int().loc["rate"]
    coefficients[city] = {
        "coef": round(m.params["rate"], 3),
        "se":   round(m.bse["rate"], 3),
        "ci_low":  round(ci[0], 3),
        "ci_high": round(ci[1], 3),
    }

# forecast chart data
fc = pd.read_csv(fc_path)
fc["date_iso"] = pd.to_datetime(fc["date"], format="%Y-%m").dt.strftime("%Y-%m-%d")
forecast = {}
for city in fc["city"].unique():
    forecast[city] = {}
    hist = df[df["city"] == city].sort_values("date_iso")
    forecast[city]["history_dates"] = hist["date_iso"].tolist()
    forecast[city]["history_mdsr"]  = (hist["mdsr"] * 100).round(2).tolist()

    for sc in ["optimistic", "baseline", "pessimistic"]:
        s = fc[(fc["city"] == city) & (fc["scenario"] == sc)].sort_values("date_iso")
        forecast[city][sc] = {
            "dates":   s["date_iso"].tolist(),
            "mdsr":    s["mdsr_pct_forecast"].round(2).tolist(),
            "ci_low":  s["ci_low"].round(2).tolist(),
            "ci_high": s["ci_high"].round(2).tolist(),
        }

# write everything as one js file
out_path.parent.mkdir(parents=True, exist_ok=True)
js = "// auto generated by 30_build_dashboard_data.py, do not edit by hand\n\n"
js += f"const AFFORDABILITY = {json.dumps(affordability, indent=2)};\n\n"
js += f"const COEFFICIENTS = {json.dumps(coefficients, indent=2)};\n\n"
js += f"const FORECAST = {json.dumps(forecast, indent=2)};\n"
out_path.write_text(js)
print(f"saved dashboard data to {out_path}")
print(f"  cities: {list(affordability.keys())}")
print(f"  history rows per city: {len(affordability['Toronto']['dates'])}")
print(f"  forecast rows per city per scenario: {len(forecast['Toronto']['baseline']['dates'])}")